package com.example.myfitplan.utils;

import java.util.HashMap;
import java.util.Map;

public class WorkoutPlanGenerator {
    public static String generateWorkoutPlan(String level, String goal) {
        Map<String, String> plans = new HashMap<>();
        // Начинающий
        plans.put("Начинающий_Похудение", "3 тренировки в неделю: кардио (бег, велосипед) + базовые силовые упражнения");
        plans.put("Начинающий_Набор массы", "3 тренировки: базовые упражнения со штангой (жим, присед, становая) + гейнер");
        plans.put("Начинающий_Поддержание формы", "3 тренировки: круговые тренировки + плавание");

        // Активный
        plans.put("Активный_Похудение", "4 тренировки: интервальные кардио-сессии + функциональный тренинг");
        plans.put("Активный_Набор массы", "4 тренировки: сплит (грудь/спина/ноги) + протеин");
        plans.put("Активный_Поддержание формы", "4 тренировки: кроссфит + йога");

        // Опытный
        plans.put("Опытный_Похудение", "5 тренировок: HIIT + силовые суперсеты");
        plans.put("Опытный_Набор массы", "6 тренировок: специализация по группам мышц + спортивное питание");
        plans.put("Опытный_Поддержание формы", "5 тренировок: функционалка + растяжка");
        return plans.getOrDefault(level + "_" + goal, "Рекомендации: потребление воды 2-2.5 литра в сутки, сон 7-8 часов ежедневно.");
    }
}